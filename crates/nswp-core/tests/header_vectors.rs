use nswp_core::{Header, HeaderFlags, NSWP_HEADER_BYTES, PacketKind, TransportStatus};

const TRACE_ID: [u8; 16] = [
    0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
];

const GOLDEN_REQUEST: [u8; NSWP_HEADER_BYTES] = [
    0x4e, 0x53, 0x57, 0x50, 0x40, 0x00, 0x01, 0x00, 0x03, 0x01, 0x00, 0x00, 0x22, 0x11, 0x44, 0x33,
    0x88, 0x77, 0x66, 0x55, 0xc0, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x08, 0x07, 0x06, 0x05, 0x04, 0x03, 0x02, 0x01, 0x18, 0x17, 0x16, 0x15, 0x14, 0x13, 0x12, 0x11,
    0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
];

fn recognizable_request() -> Header {
    Header {
        kind: PacketKind::Request,
        flags: HeaderFlags::TRACE_SAMPLED,
        protocol_major: 0x1122,
        protocol_minor: 0x3344,
        ordinal: 0x5566_7788,
        body_bytes: 0xc0,
        handle_count: 1,
        transport_status: TransportStatus::Ok,
        transaction_id: 0x0102_0304_0506_0708,
        deadline_ns: 0x1112_1314_1516_1718,
        trace_id: TRACE_ID,
    }
}

#[test]
fn request_header_matches_literal_golden_bytes() {
    let header = recognizable_request();
    let mut encoded = [0_u8; NSWP_HEADER_BYTES];
    header.encode(&mut encoded).unwrap();
    assert_eq!(encoded, GOLDEN_REQUEST);
    assert_eq!(Header::decode(&GOLDEN_REQUEST).unwrap(), header);
}

#[test]
fn prefix_decoder_rejects_short_packets() {
    assert_eq!(
        Header::decode_prefix(&GOLDEN_REQUEST[..NSWP_HEADER_BYTES - 1]),
        Err(nswp_core::DecodeError::PacketTooShort)
    );
}
