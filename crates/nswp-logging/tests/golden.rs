fn bound(minor: u16) -> BoundProtocol<'static> {
    BoundProtocol::new(
        LOGGING_PROTOCOL_ID,
        LOGGING_PROTOCOL_MAJOR,
        minor,
        ConnectionLimits::ENDPOINT_PROTOTYPE,
        1,
        &[],
    )
    .unwrap()
}

fn maximum_record<'a>(
    subsystem: &'a str,
    message: &'a str,
    wall_time: Option<u64>,
) -> LogRecord<'a> {
    LogRecord {
        event_id: EVENT_ID,
        severity: LogSeverity::Warning,
        privacy: PrivacyClass::SecuritySensitive,
        monotonic_time_ns: 123_456,
        subsystem,
        message,
        wall_time_unix_ns: wall_time,
    }
}

#[test]
fn maximum_minor_zero_record_matches_literal_160_byte_body() {
    let subsystem = "s".repeat(LOGGING_MAX_SUBSYSTEM_BYTES);
    let message = "m".repeat(LOGGING_MAX_MESSAGE_BYTES);
    let body = encode_log_record(
        maximum_record(&subsystem, &message, None),
        LOGGING_PROTOCOL_MINOR_BASE,
    )
    .unwrap();

    assert_eq!(body.as_slice(), MAX_MINOR_0_BODY);
    assert_eq!(body.len(), 160);
    let decoded = decode_log_record(body.as_slice(), &bound(LOGGING_PROTOCOL_MINOR_BASE)).unwrap();
    assert_eq!(decoded.event_id, EVENT_ID);
    assert_eq!(decoded.wall_time_unix_ns, None);
}

#[test]
fn maximum_minor_one_record_matches_literal_192_byte_body() {
    let subsystem = "s".repeat(LOGGING_MAX_SUBSYSTEM_BYTES);
    let message = "m".repeat(LOGGING_MAX_MESSAGE_BYTES);
    let body = encode_log_record(
        maximum_record(&subsystem, &message, Some(987_654)),
        LOGGING_PROTOCOL_MINOR_WALL_TIME,
    )
    .unwrap();

    assert_eq!(body.as_slice(), MAX_MINOR_1_BODY);
    assert_eq!(body.len(), MAX_BODY_BYTES);
    assert_eq!(&body.as_slice()[16..32], &EVENT_ID_BYTES);
    let decoded =
        decode_log_record(body.as_slice(), &bound(LOGGING_PROTOCOL_MINOR_WALL_TIME)).unwrap();
    assert_eq!(decoded.event_id.into_bytes(), EVENT_ID_BYTES);
    assert_eq!(decoded.subsystem, subsystem);
    assert_eq!(decoded.message, message);
    assert_eq!(decoded.wall_time_unix_ns, Some(987_654));
}

#[test]
fn protocol_profiles_preserve_endpoint_capacity_boundaries() {
    let protocol = logging_protocol();
    assert_eq!(LOGGING_PROTOCOL_MAJOR, 2);
    assert_eq!(protocol.versions.len(), 2);
    assert_eq!(protocol.versions[0].minimum_body_bytes, 160);
    assert_eq!(protocol.versions[1].minimum_body_bytes, 192);
    assert_eq!(MAX_BODY_BYTES, 192);
    assert_eq!(EVENT_ID.to_string(), "00112233-4455-4677-8899-aabbccddeeff");
}
